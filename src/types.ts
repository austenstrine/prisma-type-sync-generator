export type ScalarKind = 'scalar' | 'enum';

export type ModelFieldInfo = {
	name: string;
	kind: ScalarKind | 'object' | 'unsupported';
	type: string;
	isRequired: boolean;
	isList: boolean;
	isId: boolean;
	hasDefault: boolean;
	isUpdatedAt: boolean;
};

export type ModelInfo = {
	name: string;
	fields: ModelFieldInfo[];
};

export type EnumInfo = {
	name: string;
	values: string[];
};

export type SchemaInfo = {
	models: ModelInfo[];
	enums: EnumInfo[];
};

export type GeneratorConfig = {
	/** Destination directory for generated TypeScript. */
	outputDir: string;
	/**
	 * Optional second write root (e.g. frontend `src/generated/type-sync`).
	 * Files are copied after the primary emit — no Nest imports rewritten yet.
	 */
	copyTo?: string;
	/** Suffix for generated model classes. Default: `ModelBase`. */
	classSuffix: string;
	/** Emit `@ApiProperty` / class-validator decorators. Default: true. */
	swaggerDecorators: boolean;
	/** Include Prisma relation (object) fields. Default: false. */
	includeRelations: boolean;
	/** Header comment stamped into every generated file. */
	banner: string;
};

export const DEFAULT_CLASS_SUFFIX = 'ModelBase';

export const DEFAULT_BANNER =
	'Generated by prisma-type-sync-generator. Do not edit by hand.';

export function resolveConfig(partial: Partial<GeneratorConfig> & { outputDir: string }): GeneratorConfig {
	return {
		outputDir: partial.outputDir,
		copyTo: partial.copyTo,
		classSuffix: partial.classSuffix ?? DEFAULT_CLASS_SUFFIX,
		swaggerDecorators: partial.swaggerDecorators ?? true,
		includeRelations: partial.includeRelations ?? false,
		banner: partial.banner ?? DEFAULT_BANNER,
	};
}
